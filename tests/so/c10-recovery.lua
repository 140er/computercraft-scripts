local F=dofile("tests/so/protected.lua")
local dim="minecraft:overworld"
local frame={dim=dim,ox=0,oy=0,oz=0,rot=0}
local function setup()
  local s=F.setup({pos={dim=dim,x=0,y=0,z=0}})
  s.manualOutcome=true
  return s
end
local function reload(s)
  s.lease=s.m.env.dofile("so-mod-lease.lua")
  s.m.env.SO.mods.lease=s.lease
end
local function hello(s,id,journal,x,capabilities,pending)
  s.lease.handlers.hello({from=id,body={role="turtle",capabilities=capabilities or {parkBatch=true,setupFence=true},
    journal={id=journal,pose={x=x,y=0,z=0,f=1},pending=pending}}})
end
local function report(s,id,journal,x)
  local lid=s.lease.status(id).open
  s.lease.handlers["step.report"]({from=id,body={lease=lid,results={{ok=true}},
    pose={x=x,y=0,z=0,f=1},journal=journal}})
  assert(s.lease.ackOutcome(lid))
end
return function(test,equal)
  test("C10 flags-off restored work reconciles an advanced worker journal before the paused deadline",function()
    local s=setup()
    local old=assert(s.lease.send(2,{{op="forward"}},{owner="mine",ms=60000,frame=frame}))
    equal(s.sent[1].body.journal,"j0")
    reload(s)
    hello(s,2,"after-retreat",0)
    s.lease.tick(1000)
    equal(s.lease.outcome(2).id,old)
    equal(s.lease.outcome(2).status,"expired")
    equal(#s.sent,1,"restored movement was replayed")
    assert(s.lease.ackOutcome(old))
    assert(s.lease.send(2,{{op="inspectDown"}},{owner="mine",recover=true,frame=frame}))
    equal(s.sent[2].body.journal,"after-retreat")
    report(s,2,"stationary-fence",0)
    assert(s.lease.send(2,{{op="forward"}},{owner="mine",frame=frame}))
  end)
  test("C10 a recovered miner cannot dig a peer's retreat anchor before every restart fence saves",function()
    local s=setup()
    hello(s,3,"peer-before",2)
    assert(s.cells.reserve("mine:2",0,0,0,dim))
    assert(s.cells.reserve("lumber:3",2,0,0,dim))
    local first=assert(s.lease.send(2,{{op="forward"}},{owner="mine",ms=1000,frame=frame}))
    local peer=assert(s.lease.send(3,{{op="forward"}},{owner="lumber",ms=600000,frame=frame}))
    reload(s)
    hello(s,2,"first-returned",0)
    s.lease.tick(11001)
    assert(s.lease.ackOutcome(first))
    assert(s.lease.send(2,{{op="inspectDown"}},{owner="mine",recover=true,frame=frame}))
    report(s,2,"first-fenced",0)
    local sent=#s.sent
    local id,why=s.lease.send(2,{{op="dig"}},{owner="mine",frame=frame})
    equal(id,nil) equal(why,"restart reconciliation pending")
    equal(s.lease.send(2,{{op="dig"}},{owner="mine",recover=true,frame=frame}),nil)
    equal(#s.sent,sent,"miner dug the peer before its retreat pose was reconciled")
    equal(s.lease.status(3).open,peer)
    equal(s.cells.owner(2,0,0,dim),"lumber:3")
    hello(s,3,"peer-retreated",1)
    s.lease.tick(11002)
    assert(s.lease.ackOutcome(peer))
    assert(s.lease.send(3,{{op="inspectDown"}},{owner="lumber",recover=true,frame=frame}))
    local lid=s.lease.status(3).open
    s.lease.handlers["step.report"]({from=3,body={lease=lid,results={{ok=true}},pose={x=1,y=0,z=0,f=1},journal="peer-fenced"}})
    assert(s.cells.reserve("lumber:3",1,0,0,dim))
    s.m.capacity=1
    equal(s.lease.ackOutcome(lid),false)
    equal(s.lease.send(2,{{op="dig"}},{owner="mine",frame=frame}),nil)
    s.m.capacity=16000000
    assert(s.lease.ackOutcome(lid))
    equal(s.cells.reserve("mine:2",1,0,0,dim),false)
    assert(s.lease.send(2,{{op="back"}},{owner="mine",frame=frame}))
  end)
  test("C10 a peer's stale reservation cannot leave a recovered standing cell unowned",function()
    local s=setup()
    hello(s,3,"peer-before",2)
    assert(s.cells.reserve("mine:2",1,0,0,dim))
    assert(s.cells.reserve("lumber:3",0,0,0,dim))
    local first=assert(s.lease.send(2,{{op="forward"}},{owner="mine",frame=frame}))
    local peer=assert(s.lease.send(3,{{op="forward"}},{owner="lumber",frame=frame}))
    reload(s)
    hello(s,2,"first-retreated",0)
    s.lease.tick(1000)
    assert(s.lease.ackOutcome(first))
    local fenced=assert(s.lease.send(2,{{op="inspectDown"}},{owner="mine",recover=true,frame=frame}))
    s.lease.handlers["step.report"]({from=2,body={lease=fenced,results={{ok=true}},pose={x=0,y=0,z=0,f=1},journal="first-fenced"}})
    equal(s.lease.ackOutcome(fenced),false,"conflicting stale reservation dropped the restart barrier")
    hello(s,3,"peer-retreated",2)
    s.lease.tick(1001)
    assert(s.lease.ackOutcome(peer))
    assert(s.lease.send(3,{{op="inspectDown"}},{owner="lumber",recover=true,frame=frame}))
    assert(s.cells.release("lumber:3",0,0,0,dim))
    report(s,3,"peer-fenced",2)
    equal(s.lease.send(3,{{op="dig"}},{owner="lumber",frame=frame}),nil)
    assert(s.lease.ackOutcome(fenced))
    equal(s.cells.owner(0,0,0,dim),"mine:2")
    equal(s.cells.reserve("lumber:3",0,0,0,dim),false)
    assert(s.lease.send(3,{{op="turnRight"}},{owner="lumber",frame=frame}))
  end)
  test("C10 a late restored report cannot carry its interruption proof into a new recovery fence",function()
    local s=setup()
    local old=assert(s.lease.send(2,{{op="forward"}},{owner="mine",ms=60000,frame=frame}))
    reload(s)
    hello(s,2,"retreated",0)
    s.lease.handlers["step.report"]({from=2,body={lease=old,results={{ok=true}},pose={x=1,y=0,z=0,f=1},journal="old-report"}})
    assert(s.lease.ackOutcome(old))
    hello(s,2,"retreated",0)
    local nextId=assert(s.lease.send(2,{{op="inspectDown"}},{owner="mine",recover=true,frame=frame}))
    s.lease.tick(1000)
    equal(s.lease.status(2).open,nextId)
    report(s,2,"fenced",0)
  end)
  test("C10 a rejected journal fence cannot turn an unexecuted inspection into known air",function()
    local s=setup()
    local id=assert(s.lease.send(2,{{op="inspect"}},{owner="mine",frame=frame}))
    s.lease.handlers["step.report"]({from=2,body={lease=id,results={{ok=false,err="journal changed"}},
      pose={x=0,y=0,z=0,f=1},journal="changed"}})
    equal(s.lease.outcome(2).results,nil)
    assert(s.lease.outcome(2).hold)
    assert(s.lease.ackOutcome(id))
    equal(s.lease.send(2,{{op="dig"}},{owner="mine",recover=true,frame=frame}),nil)
    assert(s.lease.send(2,{{op="inspectDown"}},{owner="mine",recover=true,frame=frame}))
    report(s,2,"fenced",0)
  end)
  test("C10 legacy workers recover with a stationary park when boundary flags are off",function()
    local s=setup()
    hello(s,2,"legacy-before",0,{})
    local id=assert(s.lease.send(2,{{op="forward"}},{owner="mine",ms=1000,frame=frame}))
    reload(s)
    hello(s,2,"legacy-returned",0,{})
    s.lease.tick(11001)
    assert(s.lease.ackOutcome(id))
    assert(s.lease.send(2,{{op="inspectDown"}},{owner="mine",recover=true,frame=frame}))
    report(s,2,"legacy-parked",0)
    equal(s.lease.status(2).boundaryHold,nil)
    assert(s.lease.send(2,{{op="forward"}},{owner="mine",frame=frame}))
  end)
  test("C10 legacy recovery cannot bypass enabled boundary safety",function()
    local s=F.setup()
    s.manualOutcome=true
    local id=assert(s.lease.send(2,{{op="forward"}},{owner="mine",ms=1000,frame=frame}))
    reload(s)
    hello(s,2,"legacy-returned",0,{})
    s.lease.tick(11001)
    assert(s.lease.ackOutcome(id))
    local nextId,why=s.lease.send(2,{{op="inspectDown"}},{owner="mine",recover=true,frame=frame})
    equal(nextId,nil) equal(why,"restart needs fenced observation")
  end)
  test("C10 lumber retries a fleet reconciliation wait without a sticky hold",function()
    local f=dofile("tests/so/lumber-fixture.lua")("scan",1000,{})
    local ready=false
    f.mods.lease.restartReady=function() return ready end
    for i=1,3 do
      f.tick(i)
      equal(f.queued(),nil)
      equal(f.row.blocked,nil)
    end
    ready=true
    f.tick(4)
    assert(f.queued(),"lumber did not retry after peer recovery")
    equal(f.row.blocked,nil)
  end)
  test("C10 ordinary stationary park retries do not add an active-work journal fence",function()
    local s=setup()
    assert(s.lease.send(2,{{op="inspectDown"}},{owner="mine",frame=frame}))
    equal(s.sent[1].body.journal,nil)
    s.lease.tick(1000)
    equal(s.sent[2].body.lease,s.sent[1].body.lease)
    equal(s.sent[2].body.journal,nil)
  end)
  test("C10 unassigned legacy tool recovery automatically parks and unblocks its peer",function()
    local s=setup()
    local alerts={}
    s.m.env.SO.mods.state={emit=function(kind,value) if kind=="lease.alert" then alerts[#alerts+1]=value end end}
    hello(s,2,"legacy-before",0,{})
    assert(s.cells.reserve("gps:2",0,0,0,dim))
    assert(s.lease.send(2,{{op="tool",kind="pickaxe"}},{owner="tools",ms=1000}))
    reload(s)
    hello(s,2,"legacy-returned",0,{}) hello(s,3,"peer",3)
    s.now=11001 s.lease.tick(s.now)
    equal(s.lease.status(2).recovering,true)
    equal(s.lease.send(3,{{op="forward"}},{owner="mine",frame=frame}),nil)
    s.now=11002 s.lease.tick(s.now)
    local recovery=s.sent[#s.sent].body
    equal(recovery.steps,{{op="inspectDown"}})
    equal(recovery.journal,nil)
    s.lease.handlers["step.report"]({from=2,body={lease=recovery.lease,results={{ok=true}},
      pose={x=0,y=0,z=0,f=1},journal="legacy-parked"}})
    equal(s.lease.status(2).recovering,false)
    equal(s.lease.restartReady(),true)
    equal(s.cells.owner(0,0,0,dim),"gps:2")
    s.lease.tick(s.now)
    equal(alerts[#alerts],false)
    assert(s.lease.send(3,{{op="forward"}},{owner="mine",frame=frame}))
  end)
  test("C10 an absent restored worker stops holding peers after the hello bound but keeps its cells",function()
    local s=setup()
    local alerts={}
    s.m.env.SO.mods.state={emit=function(kind,value) if kind=="lease.alert" then alerts[#alerts+1]=value end end}
    assert(s.cells.reserve("mine:2",0,0,0,dim))
    assert(s.cells.reserve("mine:2",1,0,0,dim))
    local old=assert(s.lease.send(2,{{op="forward"}},{owner="mine",ms=600000,frame=frame}))
    reload(s) hello(s,3,"peer",3)
    s.lease.tick(0)
    local initialAlert=alerts[#alerts]
    s.now=59999
    equal(s.lease.restartReady(),false)
    equal(s.lease.send(3,{{op="forward"}},{owner="mine",frame=frame}),nil)
    local sent=#s.sent
    s.now=60000 s.lease.tick(s.now)
    equal(s.lease.restartReady(),true)
    equal(initialAlert.waiting,{2})
    assert(initialAlert.text:find("2",1,true))
    equal(alerts[#alerts].absent,{2})
    assert(alerts[#alerts].text:find("reservations held",1,true))
    equal(s.lease.status(2).open,old)
    equal(#s.sent,sent,"absent worker's movement was replayed")
    equal(s.cells.reserve("mine:3",0,0,0,dim),false)
    equal(s.cells.reserve("mine:3",1,0,0,dim),false)
    assert(s.lease.send(3,{{op="forward"}},{owner="mine",frame=frame}))
    report(s,3,"peer-finished",4)
    hello(s,2,"late-return",0)
    equal(s.lease.restartReady(),false,"a returning worker bypassed reconciliation")
    equal(s.lease.send(3,{{op="forward"}},{owner="mine",frame=frame}),nil)
    s.lease.tick(s.now)
    equal(alerts[#alerts].waiting,{2})
    reload(s)
    equal(s.lease.restartReady(),false,"restart did not grant a fresh hello window")
    equal(s.cells.owner(0,0,0,dim),"mine:2")
  end)
  test("C10 pending worker operations and failed close saves retain restored leases",function()
    local s=setup()
    local id=assert(s.lease.send(2,{{op="forward"}},{owner="mine",ms=60000,frame=frame}))
    reload(s)
    hello(s,2,"pending",0,nil,{op="forward"})
    s.lease.tick(1000)
    equal(s.lease.status(2).open,id)
    hello(s,2,"completed",0)
    s.m.capacity=1
    s.lease.tick(1001)
    equal(s.lease.status(2).open,id)
    equal(s.lease.send(2,{{op="forward"}},{owner="mine"}),nil)
    s.m.capacity=16000000
    s.lease.tick(1002)
    equal(s.lease.outcome(2).status,"expired")
  end)
end
