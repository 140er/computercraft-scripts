local create = dofile("tests/craftos/ar-mock.lua")
local ar, state = create()
assert(ar.drawLine3D("line", -1, 0, 0, 0, 1, 2, 3) == nil)
assert(state.elements.line.method == "drawLine3D")
ar.update()
assert(state.published.line and state.updates == 1)
ar.drawText2D("line", -1, 4, 5, "replacement", false)
assert(state.elements.line.method == "drawText2D")
assert(state.published.line.method == "drawLine3D", "update must publish a copy")
ar.delete("line")
assert(state.elements.line == nil and state.published.line ~= nil)
ar.update()
assert(next(state.published) == nil and state.updates == 2)
ar.drawRect2D("rect", -1, 0, 0, 20, 10)
ar.clear()
assert(next(state.elements) == nil)
assert(not pcall(ar.drawText2D, "bad", "color", 1, 1, "text", false))
assert(not pcall(ar.drawItemIcon3D, "bad", 0, 0, 0, 0, 0, "rotation", "minecraft:stone"))
assert(ar.unsupported == nil)
print("CraftOS AR contract: PASS (replacement, deletion, publish isolation, clear, argument shapes)")
