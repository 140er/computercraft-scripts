local handle = assert(io.open("tests/ingame/run.ps1", "rb"))
local text = handle:read("*a")
handle:close()
local function requireCap(cfg)
  local chunk = assert(load("return " .. cfg, "ssot.cfg", "t", {}))
  local value = assert(chunk())
  assert(value.maxChunks == 8, "gate B ssot scenario config is missing maxChunks=8")
end
local missing = pcall(requireCap, '{controllers={["1"]="test-secret-123456"},leaseMs=30000}')
assert(not missing, "a config without maxChunks was accepted")
local cfg = text:match('WriteAllText%("%$disk\\ssot%.cfg", \'([^\']+)\'')
assert(cfg, "gate B ssot scenario config was not found")
requireCap(cfg)
print("PASS gate B ssot.cfg sets maxChunks=8")
