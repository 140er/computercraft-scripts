return function(test,Nav,fixture)
  test("view map import is bounded and cannot turn unknown cells into walkable space",function()
    local f=fixture()
    assert(f.nav.recover())
    f.nav.import({{x=-1,y=65,z=0,name=false}},"minecraft:overworld")
    assert(f.nav.go({dim="minecraft:overworld",x=-1,y=65,z=0},"walk"))
    assert(not f.nav.go({dim="minecraft:overworld",x=0,y=65,z=0},"walk"))
    assert(not pcall(f.nav.import,{{x=0,y=65,z=0,name=false}},"minecraft:the_nether"))
    assert(not pcall(f.nav.import,{{x=0/0,y=65,z=0,name=false}},"minecraft:overworld"))
    assert(f.nav.control("view_move",1,1))
    local restored=f.reopen()
    assert(restored.recover())
    assert(not restored.control("view_move",1,1))
    assert(restored.control("estop",1,2))
    assert(not restored.control("view_move",1,1) and restored.stopped())
  end)
  test("walk finds the U route and never excavates a changed block",function()
    local f=fixture()
    for _,p in ipairs({{-2,65,0},{-1,65,0},{-2,65,1},{-1,65,1},{0,65,1},{0,65,0}}) do f.air(p) end
    assert(f.nav.recover())
    f.block(-1,65,0,"minecraft:chest")
    assert(f.nav.go({dim="minecraft:overworld",x=0,y=65,z=0},"walk"))
    f.equalPose() assert(f.digs()==0)
  end)
  test("unknown exploration and authorized excavation have separate policies",function()
    local f=fixture() assert(f.nav.recover())
    local goal={dim="minecraft:overworld",x=-1,y=65,z=0}
    assert(not f.nav.go(goal,"walk"))
    f.block(-1,65,0,"minecraft:stone")
    assert(not f.nav.step(1,"explore"))
    assert(f.nav.step(1,"excavate"))
    assert(f.digs()==1) f.equalPose()
  end)
  test("all headings and six displacements keep the physical pose",function()
    local f=fixture() assert(f.nav.recover())
    for d=0,5 do assert(f.nav.step(d,"explore")) f.equalPose() end
    assert(f.reservations()==6)
  end)
  test("search is bounded and ESTOP cancels at the next search batch",function()
    local f=fixture({maxNodes=2}) assert(f.nav.recover())
    local ok,why=f.nav.go({dim="minecraft:overworld",x=3,y=65,z=3},"explore")
    assert(not ok and why=="search budget")
    f=fixture({batch=1,onYield=function(n) n.stop() end}) assert(f.nav.recover())
    ok,why=f.nav.go({dim="minecraft:overworld",x=3,y=65,z=3},"explore")
    assert(not ok and why=="cancelled" and f.reservations()==0)
  end)
  test("failed turns, fuel, entities and fluids never invent position or solid cells",function()
    local f=fixture() assert(f.nav.recover())
    f.fault("turn") assert(not f.nav.face(0)) f.equalPose()
    f.fault("move") assert(not f.nav.step(1,"explore")) f.equalPose()
    assert(f.nav.step(1,"explore"))
    f.fuel(0) assert(not f.nav.step(4,"explore")) f.equalPose()
    f.fuel("unlimited") f.block(-1,66,0,"minecraft:water")
    assert(not f.nav.step(4,"excavate")) assert(f.digs()==0)
  end)
  test("GPS loss and relocation refuse recovery until explicit calibration",function()
    local f=fixture() assert(f.nav.recover())
    f.gps(false) assert(not f.reopen().recover())
    f.gps(true) f.relocate(2,65,2,3)
    local nav=f.reopen() assert(not nav.recover())
    assert(nav.calibrate(3)) f.equalPose()
  end)
  test("every move and turn checkpoint recovers or refuses ambiguous heading",function()
    for _,point in ipairs({"move-prepared","move-started","move-physical","move-observed","move-saved",
      "turn-prepared","turn-physical","turn-saved"}) do
      local f=fixture({crash=point}) assert(f.nav.recover())
      assert(not pcall(function()
        if point:find("turn") then f.nav.face(2) else f.nav.step(1,"explore") end
      end))
      local nav=f.reopen()
      local ok=nav.recover()
      if point=="turn-prepared" or point=="turn-physical" then
        assert(not ok) assert(nav.calibrate(f.heading()))
      else assert(ok,point) end
      f.equalPose()
    end
  end)
  test("manual movement cannot interleave and cancellation prevents the next move",function()
    local f=fixture({duringMove=function(nav)
      assert(not nav.step(4,"explore")) assert(not nav.face(0)) nav.stop()
    end})
    assert(f.nav.recover()) assert(f.nav.step(1,"explore"))
    assert(not f.nav.step(4,"explore")) f.equalPose()
  end)
  test("no route, map limits and lost GPS stop without displacement",function()
    local f=fixture({maxCells=1}) assert(f.nav.recover())
    assert(not pcall(function() f.nav.record({dim="minecraft:overworld",x=-1,y=65,z=0},"minecraft:air") end))
    f=fixture() assert(f.nav.recover())
    assert(not f.nav.go({dim="minecraft:overworld",x=0,y=65,z=0},"walk"))
    f.gps(false) assert(not f.nav.step(1,"explore")) f.equalPose()
  end)
  test("ESTOP survives reboot until an idle resume",function()
    local f=fixture() assert(f.nav.recover()) f.nav.stop()
    local nav=f.reopen() assert(nav.recover())
    assert(not nav.step(1,"explore")) assert(nav.resume())
    assert(nav.step(1,"explore")) f.equalPose()
  end)
  test("a passing turtle does not become a permanent map obstacle",function()
    local f=fixture() assert(f.nav.recover())
    f.air({-1,65,0}) f.block(-1,65,0,"computercraft:turtle_advanced")
    local ok,why=f.nav.go({dim="minecraft:overworld",x=-1,y=65,z=0},"walk")
    assert(not ok and why=="occupied")
    f.block(-1,65,0,nil)
    assert(f.nav.go({dim="minecraft:overworld",x=-1,y=65,z=0},"walk")) f.equalPose()
  end)
  test("GPS loss after a physical move leaves a recoverable uncertain action",function()
    local f
    f=fixture({duringMove=function() f.gps(false) end})
    assert(f.nav.recover())
    assert(not pcall(function() f.nav.step(1,"explore") end))
    f.gps(true) assert(f.reopen().recover()) f.equalPose()
  end)
  test("falling blocks and charging stations stop excavation without moving",function()
    local f=fixture({falling=true}) assert(f.nav.recover())
    f.block(-1,65,0,"minecraft:stone")
    local ok,why=f.nav.step(1,"excavate")
    assert(not ok and why=="falling block" and f.digs()==1) f.equalPose()
    f=fixture() assert(f.nav.recover())
    f.block(-1,65,0,"superbwarfare:charging_station")
    assert(not f.nav.step(1,"excavate") and f.digs()==0) f.equalPose()
  end)
  test("an interrupted calibration retries its original prior pose after reboot",function()
    local f=fixture() assert(f.nav.recover())
    f.relocate(2,65,2,3) f.fault("calibration")
    assert(not f.nav.calibrate(3))
    assert(f.reopen().recover()) f.equalPose()
  end)
  test("late and replayed movement commands cannot clear a newer ESTOP",function()
    local f=fixture() assert(f.nav.recover())
    assert(f.nav.control("estop",1,2))
    assert(not f.nav.control("go",1,1) and f.nav.stopped())
    local nav=f.reopen() assert(nav.recover())
    assert(not nav.control("go",1,1) and nav.stopped())
    assert(nav.control("go",1,3) and not nav.stopped())
    assert(nav.control("estop",2,1))
    assert(not nav.control("go",1,100) and nav.stopped())
  end)
  test("a queued resume waits for the active move and a newer ESTOP cancels it",function()
    for _,stopAgain in ipairs({false,true}) do
      local f=fixture({duringMove=function(nav)
        assert(nav.control("estop",1,2))
        assert(nav.control("go",1,3))
        assert(nav.stopped() and not nav.resumePending())
        if stopAgain then assert(nav.control("estop",1,4)) end
      end})
      assert(f.nav.recover()) assert(f.nav.step(1,"explore"))
      assert(f.nav.resumePending()==not stopAgain)
      assert(f.nav.stopped()==stopAgain) f.equalPose()
    end
  end)
  test("authenticated boot sync rejects commands from an older server epoch",function()
    local f=fixture({epoch="2"}) assert(f.nav.recover()) f.nav.stop()
    assert(not f.nav.control("go",1,100) and f.nav.stopped())
    assert(f.nav.control("go",2,1) and not f.nav.stopped())
  end)
end
